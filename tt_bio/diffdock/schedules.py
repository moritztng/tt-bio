"""The two score-norm tables the output heads scale by.

``scale_by_sigma`` divides the translation head by ``tr_sigma``, multiplies the rotation head
by ``so3.score_norm(rot_sigma)`` and the torsion head by ``sqrt(torus.score_norm(tor_sigma))``.
Those last two are upstream's only numerical data dependencies outside the checkpoint, and
upstream ships neither: it recomputes them on first import and caches them as hidden ``.npy``
files in the working directory (``.so3_*4.npy``, ``.p.npy``, ``.score.npy`` — 460 MB). tt-bio
ships the two 1-D curves that are actually used, as ``score_norm_tables.json``, generated by
``scripts/diffdock_port/gen_score_norms.py``. Same pattern as ``w3j_tables.json``: ship the
table, not the generator.

Both lookups are *rounded* grid indices, so each scaling is a step function of sigma. That is
upstream's behaviour and it is load-bearing — two sigmas a thousandth apart can land on
different steps — so it is reproduced rather than smoothed.

**SO(3) is deterministic; reproducing it needs upstream's summation order.** The IGSO(3)
series cancels catastrophically at large omega, where the true density is ~0: at
``eps = 0.14`` the summed ``f(w)`` reaches ``-5e-14`` against a peak of ``1.7e3``. Summing it
as a matrix product — mathematically the same sum, and the obvious way to turn a 2 h loop into
seconds — reassociates those terms and the ``df/f`` that follows explodes: 136 of the 879
reachable grid points came out wrong, by up to 1e130, and the curve grew spikes (second
difference 5e144 against upstream's 1.2e-4). Precomputing the angular factors once and
keeping upstream's elementwise-then-``sum(0)`` order is just as fast and reproduces upstream
to **2.7e-11 max relative over the reachable range** (median 2.6e-14), with the same 19
non-finite entries at eps the model never reaches. BLAS reassociation is safe for a sum that
does not cancel; this one cancels by 17 orders of magnitude.

**The torus table is Monte Carlo, and unseeded.** ``utils/torus.py`` estimates
``E[score(x, sigma)^2]`` with 10 000 draws at import time, with no seed anywhere on the path,
so the number upstream uses differs from process to process — the ``.p.npy`` cache merely
freezes whichever run created it. Measured over three upstream processes: **median 0.8 %,
up to 3.6 % relative spread** (run-to-run, per grid point). So there is no bit-exact target
here, and grading against one upstream process would be grading against a sample. The table
shipped here is the deterministic quadrature of the same expectation; the bar is that it sits
inside upstream's run-to-run spread, which ``tests/test_diffdock_schedules.py`` checks.
"""

from __future__ import annotations

import json
import math
from functools import lru_cache
from pathlib import Path

import numpy as np
import torch
from torch import Tensor

# Upstream's grids. These fix the quantisation of both lookups, not just their range.
SO3_MIN_EPS, SO3_MAX_EPS, SO3_N_EPS = 0.0005, 4.0, 2000
SO3_X_N = 2000
SO3_L = 2000
TORUS_X_MIN, TORUS_X_N = 1e-5, 5000                                  # relative to pi
TORUS_SIGMA_MIN, TORUS_SIGMA_MAX, TORUS_SIGMA_N = 3e-3, 2.0, 5000    # relative to pi

_TABLE_PATH = Path(__file__).with_name("score_norm_tables.json")


@lru_cache(maxsize=1)
def _tables() -> dict:
    return json.loads(_TABLE_PATH.read_text())


def so3_eps_grid() -> np.ndarray:
    return 10 ** np.linspace(math.log10(SO3_MIN_EPS), math.log10(SO3_MAX_EPS), SO3_N_EPS)


def torus_sigma_grid() -> np.ndarray:
    return 10 ** np.linspace(math.log10(TORUS_SIGMA_MIN), math.log10(TORUS_SIGMA_MAX),
                             TORUS_SIGMA_N + 1) * np.pi


def compute_so3_score_norms() -> np.ndarray:
    """``[N_EPS]`` RMS IGSO(3) score, in float64, in upstream's summation order.

    The order is not an implementation detail here — see the module docstring. The angular
    factors are precomputed once (upstream rebuilds them per eps, which is what makes its
    version a two-hour job), but the per-eps reduction stays ``(decay * H).sum(0)``.
    """
    eps_grid = so3_eps_grid()
    omega = np.linspace(0, np.pi, SO3_X_N + 1)[1:]
    l = np.arange(SO3_L, dtype=np.float64).reshape(-1, 1)
    lo, dlo = np.sin(omega / 2), 0.5 * np.cos(omega / 2)
    hi = np.sin((l + 0.5) * omega)
    dhi = (l + 0.5) * np.cos((l + 0.5) * omega)
    h, dh = hi / lo, (lo * dhi - hi * dlo) / lo ** 2
    weight = (1 - np.cos(omega)) / np.pi
    out = np.empty(SO3_N_EPS)
    old = np.seterr(all="ignore")       # the cancellation is expected; upstream warns too
    try:
        for i, eps in enumerate(eps_grid):
            decay = (2 * l + 1) * np.exp(-l * (l + 1) * eps ** 2 / 2)
            f = (decay * h).sum(0)
            df = (decay * dh).sum(0)
            pdf = f * weight
            out[i] = np.sqrt(((df / f) ** 2 * pdf).sum() / pdf.sum() / np.pi)
    finally:
        np.seterr(**old)
    return out


def compute_torus_score_norms(quad_points: int = 20001, wraps: int = 100) -> np.ndarray:
    """``[SIGMA_N + 1]`` mean square wrapped-normal score, by quadrature not by sampling."""
    sigma = torus_sigma_grid()
    x = np.linspace(-np.pi, np.pi, quad_points)
    n = np.arange(-wraps, wraps + 1).reshape(-1, 1)
    shifted = x + 2 * np.pi * n
    out = np.empty(sigma.size)
    for i, s in enumerate(sigma):
        w = np.exp(-shifted ** 2 / 2 / s ** 2)
        p = w.sum(0)
        grad = (-shifted / s ** 2 * w).sum(0)
        score = grad / (p + np.finfo(np.float64).eps)
        out[i] = np.trapz(score ** 2 * p, x) / np.trapz(p, x)
    return out


@lru_cache(maxsize=1)
def so3_score_norm_table() -> np.ndarray:
    return np.asarray(_tables()["so3_score_norm"], dtype=np.float64)


@lru_cache(maxsize=1)
def torus_score_norm_table() -> np.ndarray:
    return np.asarray(_tables()["torus_score_norm"], dtype=np.float64)


def so3_score_norm(eps: Tensor) -> Tensor:
    """Upstream's ``utils.so3.score_norm``: a rounded lookup, never an interpolation."""
    e = eps.detach().cpu().numpy()
    idx = (np.log10(e) - math.log10(SO3_MIN_EPS)) / (
        math.log10(SO3_MAX_EPS) - math.log10(SO3_MIN_EPS)) * SO3_N_EPS
    idx = np.clip(np.around(idx).astype(int), 0, SO3_N_EPS - 1)
    return torch.from_numpy(so3_score_norm_table()[idx]).float().to(eps.device)


def torus_score_norm(sigma) -> np.ndarray:
    """Upstream's ``utils.torus.score_norm``: a rounded lookup on a log-spaced sigma grid."""
    s = sigma.detach().cpu().numpy() if isinstance(sigma, Tensor) else np.asarray(sigma)
    idx = (np.log(s / np.pi) - math.log(TORUS_SIGMA_MIN)) / (
        math.log(TORUS_SIGMA_MAX) - math.log(TORUS_SIGMA_MIN)) * TORUS_SIGMA_N
    idx = np.round(np.clip(idx, 0, TORUS_SIGMA_N)).astype(int)
    return torus_score_norm_table()[idx]
