def patch_in0(src: str) -> str:
    src = sub(src, "const uint32_t in0_addr = get_arg_val<uint32_t>(argidx++);",
              "const uint32_t in0_addr = get_arg_val<uint32_t>(argidx++);\n"
              "    // TRIMUL_TAIL: pass 1's activation rides in the unused in2 slot, so the runtime\n"
              "    // arg layout mm_generic.rebind depends on is unchanged.",
              "in0 addr decl")
    src = sub(src, "const auto in0_reader = TensorAccessor(in0_args, in0_addr, in0_tile_size);",
              "const auto in0_reader = TensorAccessor(in0_args, in0_addr, in0_tile_size);\n"
              "    const auto in0b_reader = TensorAccessor(in0_args, in2_addr, in0_tile_size);",
              "in0 accessor")
    src = sub(src, "            for (uint32_t k_block_iter = 0; k_block_iter < K_num_blocks; k_block_iter++) {",
              "            for (uint32_t pass = 0; pass < TRIMUL_TAIL_PASSES; pass++) {\n"
              "            for (uint32_t k_block_iter = 0; k_block_iter < K_num_blocks; k_block_iter++) {",
              "in0 k loop open")
    src = sub(src, "if (defer_write && k_block_iter == defer_write_k_block) {",
              "if (defer_write && pass == 0 && k_block_iter == defer_write_k_block) {",
              "in0 defer guard")
    src = sub(src, "if (reuse_block && k_block_iter == 0) {",
              "if (reuse_block && pass == 0 && k_block_iter == 0) {",
              "in0 reuse guard")
    src = sub(src, """                    read_in0_block_sync<M_block_tiles, K_block_tiles>(
                        in0_reader,""",
              """                    read_in0_block_sync<M_block_tiles, K_block_tiles>(
                        pass == 0 ? in0_reader : in0b_reader,""",
              "in0 read call")
    src = sub(src, K_LOOP_CLOSE, K_LOOP_CLOSE_NEW, "in0 k loop close")
    return HEADER + src


