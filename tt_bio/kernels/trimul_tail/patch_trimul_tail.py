def patch_compute(src: str) -> str:
    src = sub(src, '#include "api/compute/eltwise_binary_sfpu.h"',
              '#include "api/compute/eltwise_binary_sfpu.h"\n' + COMPUTE_PROLOGUE,
              "compute includes")
    src = sub(src, """    constexpr uint32_t in2_cb = tt::CBIndex::c_4;
    constexpr uint32_t ternary_a_cb = tt::CBIndex::c_5;
    constexpr uint32_t ternary_b_cb = tt::CBIndex::c_6;""",
              """    constexpr uint32_t in2_cb = tt::CBIndex::c_4;
    constexpr uint32_t ternary_a_cb = tt::CBIndex::c_5;
    constexpr uint32_t ternary_b_cb = tt::CBIndex::c_6;

    // TRIMUL_TAIL: the two bf16 GEMM results and the rounded gate, one output block each.
    constexpr uint32_t p_cb = tt::CBIndex::c_4;
    constexpr uint32_t g_cb = tt::CBIndex::c_5;
    constexpr uint32_t sig_cb = tt::CBIndex::c_6;

    sigmoid_tile_init();""",
              "compute cb decls")
    src = sub(src, COMPUTE_BODY_OLD, COMPUTE_BODY_NEW, "compute block body")
    src = sub(src, COMPUTE_DRAIN_OLD, COMPUTE_DRAIN_NEW, "compute drain")
    return HEADER + src


def main() -> int:
    kd = wheel_kernel_dir()
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "matmul_dataflow_common.hpp").write_text(
        (kd / "matmul_dataflow_common.hpp").read_text())
    (OUT / "dm_in0_sender.cpp").write_text(patch_in0((kd / "dm_in0_sender.cpp").read_text()))
    (OUT / "dm_in1_sender_out.cpp").write_text(patch_in1((kd / "dm_in1_sender_out.cpp").read_text()))
    (OUT / "compute.cpp").write_text(patch_compute((kd / "compute.cpp").read_text()))
    print(f"generated from {kd}")
    for f in ("matmul_dataflow_common.hpp", "dm_in0_sender.cpp", "dm_in1_sender_out.cpp",
              "compute.cpp"):
        print(f"  {f:28s} {len((OUT / f).read_text().splitlines())} lines")
    return 0


if __name__ == "__main__":
    sys.exit(main())
