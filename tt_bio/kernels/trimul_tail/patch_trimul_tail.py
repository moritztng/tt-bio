def sub(text: str, old: str, new: str, what: str, count: int = 1) -> str:
    n = text.count(old)
    if n != count:
        raise SystemExit(f"anchor '{what}' matched {n} times, expected {count}. Wheel moved.")
    return text.replace(old, new, count)


