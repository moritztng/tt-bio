COMPUTE_PROLOGUE = """
// ---------------------------------------------------------------- TRIMUL_TAIL: the gate epilogue
#include "api/compute/eltwise_binary_sfpu.h"

#ifdef TRISC_MATH
#include "llk_math_eltwise_unary_sfpu_params.h"
#include "sfpi.h"

namespace ckernel {
namespace sfpu {
// Round DST to bf16 in the SFPU with the SAME rounding the 16-bit DST store uses, so the pack that
// follows cannot round again. Under fp32 DST the packer breaks ties away from zero where ttnn's
// binary_ng breaks them to even; E6 measured that as 0.91 % of elements at a 1.85 % tie rate.
template <int ITERATIONS = 8>
inline void _round_bf16_() {
#pragma GCC unroll 8
    for (int d = 0; d < ITERATIONS; d++) {
        sfpi::vFloat v = sfpi::dst_reg[0];
#if TRIMUL_TAIL_ROUND == 2
        // The same round-to-nearest-even by hand, in case the SFPSTOCHRND path does not land
        // where reinterpret<vFloat> expects it.
        sfpi::vUInt u = sfpi::reinterpret<sfpi::vUInt>(v);
        sfpi::vUInt lsb = (u >> 16) & 1;
        u = u + 0x7FFF;
        u = u + lsb;
        u = (u >> 16) << 16;
        sfpi::dst_reg[0] = sfpi::reinterpret<sfpi::vFloat>(u);
#else
        sfpi::dst_reg[0] = sfpi::reinterpret<sfpi::vFloat>(
            sfpi::float_to_fp16b(v, sfpi::RoundMode::NearestEven));
#endif
        sfpi::dst_reg++;
    }
}
}  // namespace sfpu
}  // namespace ckernel
#endif  // TRISC_MATH

ALWI void round_bf16_tile(uint32_t idst) {
    // `_llk_math_eltwise_unary_sfpu_params_` is a global template, not a member of `ckernel`.
    MATH((_llk_math_eltwise_unary_sfpu_params_<false>(
        ckernel::sfpu::_round_bf16_<8>, idst, (int)VectorMode::RC)));
}

// sigmoid on the bf16 branch, asked for explicitly. `sigmoid_tile` hard-wires DST_ACCUM_MODE and
// would take the accurate branch, which is not what ttnn.multiply_(..., SIGMOID) computes.
ALWI void sigmoid_bf16_tile(uint32_t idst) {
    MATH((llk_math_eltwise_unary_sfpu_sigmoid<false, false>(idst, (int)VectorMode::RC)));
}

// out = p * sigmoid(g), tile by tile, in the order and with the rounding points production uses:
// sigmoid is rounded to bf16 BEFORE the multiply (binary_ng applies an input activation in
// PREPROCESS, which packs the activated operand before the binary op unpacks it again), and the
// multiply is the SFPU one (the FPU's mul_tiles truncates the product).
void gate_block(
    uint32_t p_cb, uint32_t g_cb, uint32_t sig_cb, uint32_t out_cb, uint32_t block_num_tiles) {
    for (uint32_t t = 0; t < block_num_tiles; t++) {
        cb_reserve_back(sig_cb, 1);
        tile_regs_acquire();
        copy_tile_to_dst_init_short(g_cb);
        reconfig_data_format_srca(g_cb);
        pack_reconfig_data_format(sig_cb);
        copy_tile(g_cb, t, 0);
#if TRIMUL_TAIL_SKIP_SIGMOID == 0
        sigmoid_bf16_tile(0);
#endif
        tile_regs_commit();
        tile_regs_wait();
        pack_tile(0, sig_cb);
        tile_regs_release();
        cb_push_back(sig_cb, 1);

        cb_wait_front(sig_cb, 1);
        tile_regs_acquire();
        copy_tile_to_dst_init_short(p_cb);
        reconfig_data_format_srca(p_cb);
        pack_reconfig_data_format(out_cb);
        copy_tile(p_cb, t, 0);
        copy_tile_to_dst_init_short(sig_cb);
        copy_tile(sig_cb, 0, 1);
        mul_binary_tile_init();
        mul_binary_tile(0, 1, 0);
#if TRIMUL_TAIL_ROUND != 0
        round_bf16_tile(0);
#endif
        tile_regs_commit();
        tile_regs_wait();
        pack_tile(0, out_cb);
        tile_regs_release();
        cb_pop_front(sig_cb, 1);
    }
    cb_push_back(out_cb, block_num_tiles);
}
"""

