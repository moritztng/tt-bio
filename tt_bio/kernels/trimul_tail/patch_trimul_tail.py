#!/usr/bin/env python3
"""Generate `tt_bio/kernels/trimul_tail/` from the installed wheel's own minimal_matmul kernels.

F1 fuses the trimul output tail's two projections and its gate into one `generic_op`:

    production   layer_norm -> p_out = x_norm @ Wp -> g_out = x_norm_in @ Wg
                            -> multiply_(p_out, g_out, SIGMOID on b)          4P read, 3P write
    F1           layer_norm -> one kernel over (x_norm, Wp) and (x_norm_in, Wg)
                            -> sigmoid + multiply inside the core              2P read, 1P write

At the tail's block config `_MM_BLOCK[8] = (4, 8, 1, 4, 1)` the contraction is one K block
(`K_tiles == K_block_tiles == 8`), so the two GEMMs cannot interact through the cross-block L1
accumulator and the fusion is an extra PASS around the existing inner loop, not a new dataflow:

    for each output block:
        pass 0   K loop on (in0_a, in1_a) -> intermediate_cb -> copy_block -> cb_p   (bf16)
        pass 1   K loop on (in0_b, in1_b) -> intermediate_cb -> copy_block -> cb_g   (bf16)
        gate     sigmoid(cb_g) -> cb_sig ; cb_p * cb_sig -> round bf16 -> cb_out

`x_norm` and `x_norm_in` share shape, dtype, layout and memory config, so both passes share one
`TensorAccessorArgs` and differ only in the base address; likewise the two weights. The second
address rides in the unused `in2_addr` runtime slot, so the arg layout `mm_generic.rebind` depends
on is untouched.

Three rounding points are load-bearing and each mirrors what production does today. Two are E6's,
measured (`tt_bio/kernels/reblock_permute_gated/compute_reblock_permute_gated.cpp`); the third is
new to F1 and exists because F1, unlike E6, must run fp32 DST for the GEMM:

  * p and g are packed from the fp32 accumulator to bf16 through the wheel's own `copy_block`,
    which is the identical pack that writes `p_out` and `g_out` to DRAM today.
  * the sigmoid is instantiated as `llk_math_eltwise_unary_sfpu_sigmoid<false, false>` -- the
    SECOND template argument, not the descriptor's DST width. `sigmoid_tile` hard-wires
    `DST_ACCUM_MODE` and would take the accurate branch, which E6 measured as a full bf16 ulp off
    ttnn on 10.4 % of elements. The bf16 branch ends in `float_to_fp16b(result, 0)`, so what
    reaches the packer is already exactly a bf16 and the pack cannot round it again.
  * the product is rounded to bf16 IN THE SFPU by `round_bf16_tile`, with the same
    `float_to_fp16b(v, 0)`, before it is packed. Under fp32 DST the packer breaks ties away from
    zero where ttnn's 16-bit DST store breaks them to even; E6 measured that as 0.91 % of elements
    at a 1.85 % tie rate. Rounding first makes the pack exact by construction.

Regenerate after any wheel bump: the sources are read from the installed wheel, so a moved anchor
raises here instead of binding a stale kernel silently.
"""
